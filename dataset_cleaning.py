"""# Práctica 16:
* Genera el diccionario de datos del dataframe preprocesado.
* Imprime el contenido de dicho diccionario
"""

import pandas as pd

# Load and prepare the data
df = pd.read_csv('/content/drive/MyDrive/ClassFiles/miaad-nyc-r-s.csv', skipfooter=1, engine='python') #skip last row
df.rename(columns={df.columns[0]: 'INDEX MIAAD'}, inplace=True) # rename first colum (variable name)
df.columns = [col.lower().replace(' ', '_') for col in df.columns] # normalize column's names

""" Make sure again the floating columns are written correctly,
    change them again using a loop;
    it's easier now since you don't need to check them and print those needed.
"""

float_cols = ['sale_price', 'land_square_feet', 'gross_square_feet']
for col in float_cols:
    if col in df.columns:
        df[col] = pd.to_numeric(df[col], errors='coerce').astype('float64')

# 1. Generate a simple data dictionary from preprocessed dataframe
# Store the datadictionary using a Dictionary
data_dict = {}
"""
the key is going to be the column's name, and its values the column's associated information,
so each pair becomes an entry in the final dataset Dictionary
"""
# its is easier to do, just iterate through the dataframe columns,
## then build an entry of the dictionary
# insert that entry into the data_dict dictionary
#all the valid information to build the dictionary entries are in each variable column
# just use pandas dataframe built-in functions to ask for
for col in df.columns:
    data_dict[col] = {
        'dtype': df[col].dtype, #data type of the variable column
        'non_null_count': df[col].count(), # how much not null values has that variable column
        'null_count': df[col].isnull().sum(), #to count null values in current column
        'null_percentage': round(df[col].isnull().sum() / len(df) * 100, 2), # to save percentage of null values in current column
        'unique_values': df[col].nunique() # how many different variable's values can be or has been assigned
    }

    # Add sample values for context, sample values are possible values taken from current ones
    # it adds a sample of 3 current values : min (3,...) or [] if not sample values to keep
    sample_values = df[col].dropna().sample(min(3, df[col].count())).tolist() if df[col].count() > 0 else []
    data_dict[col]['samples'] = sample_values

    # Add numeric stats for numerical variable columns
    # new columns min, max, meann, std are added on the fly
    # once again, information is gotten from built-in functions of pandas dataframe
    if pd.api.types.is_numeric_dtype(df[col]):
        data_dict[col]['min'] = df[col].min()
        data_dict[col]['max'] = df[col].max()
        data_dict[col]['mean'] = round(df[col].mean(), 2)
        data_dict[col]['std'] = round(df[col].std(), 2)

# 2. Print the contents of the Dictionary in a readable way
print("=" * 60)
display(Markdown("###  DATA DICTIONARY"))
display(Markdown("*Variable names are changed to uppercase*"))
print("=" * 60)


for col_name, col_info in data_dict.items(): # iterate through the dictionary list
    print(f"\n {col_name.upper()}")
    print("-" * 40)
    for key, value in col_info.items(): # each element is itself a dictionary
        print(f"  {key}: {value}")

